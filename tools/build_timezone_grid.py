"""Build the GPS clock time zone grid in patches/capture-04/etc/common/Global.qml.

Input: timezone-boundary-builder timezones-now.geojson.zip (OpenStreetMap data, ODbL 1.0).
Download: gh release download 2026e -R evansiroky/timezone-boundary-builder -p timezones-now.geojson.zip

The grid covers North America. Each cell holds one zone class: a standard UTC offset and whether the zone keeps the
US and Canada daylight saving time rule. Zones with any other rule (for example Cuba) stay empty, so the clock keeps the
last zone there instead of a guess. Classes come from the Python zoneinfo rules, checked for every year in YEARS.

Usage: python tools/build_timezone_grid.py ZIP [--check]
--check fails when Global.qml does not match the grid this input builds.
"""
import argparse
import hashlib
import importlib.metadata
import json
import sys
import zipfile
from datetime import datetime, timedelta, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "patches/capture-04/etc/common/Global.qml"
RELEASE = "2026e"
SOUTH, WEST, STEP, ROWS, COLS = 14.0, -180.0, 0.05, 1160, 2600
YEARS = range(2026, 2036)
BEGIN = "    // gpsClockGrid begin"
END = "    // gpsClockGrid end\n"


def us_rule(year, std):
    """UTC instants where the US and Canada rule starts and ends daylight saving time, for a standard offset in minutes."""
    march = datetime(year, 3, 1, tzinfo=timezone.utc)
    start = march + timedelta(days=(6 - march.weekday()) % 7 + 7, hours=2, minutes=-std)
    november = datetime(year, 11, 1, tzinfo=timezone.utc)
    end = november + timedelta(days=(6 - november.weekday()) % 7, hours=2, minutes=-(std + 60))
    return start, end


def zone_class(tzid):
    """(standard offset in minutes, keeps the US rule) for a zone id, or None for any other rule."""
    tz = ZoneInfo(tzid)
    offset = lambda t: round(t.astimezone(tz).utcoffset().total_seconds() / 60)
    std = offset(datetime(2026, 1, 15, 12, tzinfo=timezone.utc))
    dst = offset(datetime(2026, 7, 15, 12, tzinfo=timezone.utc)) != std
    for year in YEARS:
        start, end = us_rule(year, std)
        day = datetime(year, 1, 1, tzinfo=timezone.utc)
        while day.year == year:
            for t in (day, day + timedelta(hours=12)):
                expected = std + 60 if dst and start <= t < end else std
                if offset(t) != expected:
                    return None
            day += timedelta(days=1)
        if dst and (offset(start - timedelta(seconds=1)) != std or offset(start) != std + 60
                    or offset(end - timedelta(seconds=1)) != std + 60 or offset(end) != std):
            return None
    return std, int(dst)


def area(ring):
    return abs(sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(ring, ring[1:] + ring[:1]))) / 2


def build(zip_path):
    data = Path(zip_path).read_bytes()
    with zipfile.ZipFile(zip_path) as archive:
        features = json.loads(archive.read(archive.namelist()[0]))["features"]
    classes, polygons = {}, []
    for feature in features:
        geometry = feature["geometry"]
        parts = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        inside = [p for p in parts if any(WEST <= x <= -50 and SOUTH <= y <= SOUTH + ROWS * STEP for x, y in p[0])]
        if not inside:
            continue
        cls = zone_class(feature["properties"]["tzid"])
        value = 0 if cls is None else classes.setdefault(cls, len(classes) + 1)
        polygons += [(area(p[0]), value, p) for p in inside]
    if len(classes) > 26:
        raise SystemExit("More than 26 zone classes")
    image = Image.new("L", (COLS, ROWS), 0)
    draw = ImageDraw.Draw(image)
    cell = lambda ring: [((x - WEST) / STEP, (y - SOUTH) / STEP) for x, y in ring]
    # Largest first, so enclaves (smaller polygons) draw over the zone around them. Holes clear to "no zone".
    for _, value, polygon in sorted(polygons, key=lambda item: -item[0]):
        draw.polygon(cell(polygon[0]), fill=value)
        for hole in polygon[1:]:
            draw.polygon(cell(hole), fill=0)
    pixels = image.load()
    rows = []
    for r in range(ROWS):
        runs, last, count = [], None, 0
        for c in range(COLS):
            v = pixels[c, r]
            if v == last:
                count += 1
                continue
            if last is not None:
                runs.append(("." if last == 0 else chr(96 + last)) + str(count))
            last, count = v, 1
        runs.append(("." if last == 0 else chr(96 + last)) + str(count))
        rows.append("".join(runs))
    zones = [list(cls) for cls, _ in sorted(classes.items(), key=lambda item: item[1])]
    lines = [
        BEGIN + ": generated by tools/build_timezone_grid.py. Do not edit.",
        f"    // Source: timezone-boundary-builder {RELEASE} timezones-now.geojson.zip, sha256 {hashlib.sha256(data).hexdigest()}.",
        f"    // Zone rules: Python zoneinfo with tzdata {importlib.metadata.version('tzdata')}, checked for {YEARS.start} to {YEARS.stop - 1}.",
        "    // Data (c) OpenStreetMap contributors, Open Database License 1.0 (https://opendatacommons.org/licenses/odbl/1-0/).",
        f"    // Grid: south edge {SOUTH}, west edge {WEST}, cell {STEP} degree, {ROWS} rows from south to north, {COLS} columns.",
        "    // Each row is runs of a zone letter (a = gpsClockZones[0]) or \".\" (no zone) and a cell count.",
        "    // gpsClockZones: [standard UTC offset in minutes, 1 = US and Canada daylight saving time rule].",
        "    readonly property var gpsClockZones: " + json.dumps(zones, separators=(",", ":")),
        f"    readonly property var gpsClockGridSpec: [{SOUTH},{WEST},{STEP},{ROWS},{COLS}]",
        "    readonly property var gpsClockGrid: [",
        *[f'        "{row}",' for row in rows],
        "    ]",
        END,
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("zip")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    block = build(args.zip)
    text = TARGET.read_text(encoding="utf-8")
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < 0:
        raise SystemExit("Global.qml has no gpsClockGrid markers")
    updated = text[:start] + block + text[end + len(END):]
    if args.check:
        sys.exit(0 if updated == text else "Global.qml grid differs from the input")
    TARGET.write_text(updated, encoding="utf-8", newline="\n")
    print(json.dumps({"bytes": len(block.encode()), "zones": block.split("property var gpsClockZones: ")[1].split("\n")[0]}))


if __name__ == "__main__":
    main()
